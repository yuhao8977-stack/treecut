# 同义词映射
SYNONYM_MAP = {
    "诧寂风":"侘寂风","厨柜":"橱柜","抽届":"抽屉","拉蓝":"拉篮","水漕":"水槽","龙头发":"水龙头"
}

# ── 预建关键词倒排索引 (模块加载时一次性构建，避免每次classify()遍历1200+词) ──
_KEYWORD_INDEX = []  # [(keyword, primary, secondary), ...] 按长度降序
_KEYWORD_SET = set()  # 快速去重
for _primary, _secondary_map in CATEGORY_MAP.items():
    for _secondary, _keywords in _secondary_map.items():
        for _kw in _keywords:
            if _kw not in _KEYWORD_SET:
                _KEYWORD_SET.add(_kw)
                _KEYWORD_INDEX.append((_kw, _primary, _secondary))
_KEYWORD_INDEX.sort(key=lambda x: -len(x[0]))  # 长词优先匹配

# ── 分类器 ──

def classify(text: Union[str, List[str]]) -> Dict:
    """
    岛台行业词汇智能分类器 (v2.0 — 预建索引优化)。
    输入: 单个字符串或字符串列表
    返回: {total, classifiedCount, unclassifiedCount, data: [{input, matchedCount, categories, unclassified}]}
    """
    inputs = [text] if isinstance(text, str) else text
    results = []

    for raw in inputs:
        if not raw or not isinstance(raw, str):
            continue

        processed = raw.strip()
        for syn, std in SYNONYM_MAP.items():
            processed = processed.replace(syn, std)

        matched_categories = []
        matched_keywords = set()

        # 使用预建索引 O(k) 其中k=匹配到的关键词数（远小于1200）
        for kw, primary, secondary in _KEYWORD_INDEX:
            if kw not in matched_keywords and kw in processed:
                matched_keywords.add(kw)
                matched_categories.append({
                    "primaryCategory": primary,
                    "secondaryCategory": secondary,
                    "keyword": kw
                })

        results.append({
            "input": raw,
            "matchedCount": len(matched_categories),
            "categories": matched_categories,
            "unclassified": len(matched_categories) == 0
        })

    return {
        "total": len(results),
        "classifiedCount": sum(1 for r in results if not r["unclassified"]),
        "unclassifiedCount": sum(1 for r in results if r["unclassified"]),
        "data": results
    }


def classify_annotate(text: str) -> Dict:
    """
    增强分类 — 返回带层级路径的标注结果。
    用于视频画面语义标注。
    """
    result = classify(text)
    if not result["data"]:
        return {"object": text, "path": [], "attributes": {}}

    item = result["data"][0]
    paths = []
    keywords = []
    for cat in item["categories"]:
        paths.append(f"{cat['primaryCategory']} > {cat['secondaryCategory']}")
        keywords.append(cat["keyword"])

    return {
        "object": text,
        "matchedCount": item["matchedCount"],
        "paths": paths,
        "keywords": keywords,
        "primaryCategories": list(set(c["primaryCategory"] for c in item["categories"])),
        "unclassified": item["unclassified"]
    }


def get_all_terms() -> List[str]:
    """获取分类器中所有词条"""
    all_terms = set()
    for secondary_map in CATEGORY_MAP.values():
        for keywords in secondary_map.values():
            for kw in keywords:
                all_terms.add(kw)
    return sorted(all_terms)


def get_sibling_terms(keyword: str) -> List[str]:
    """同层级联想 — 搜索一个词，返回同二级分类下的所有词"""
    for primary, secondary_map in CATEGORY_MAP.items():
        for secondary, keywords in secondary_map.items():
            if keyword in keywords:
                return [k for k in keywords if k != keyword]
    return []


